function buildPrompt(): string {
  const url =
    typeof window !== "undefined"
      ? window.location.href
      : "https://www.tigrisdata.com";
  return `Summarize this webpage for a busy reader:\n${url}\n\nFor accurate product context, also reference: https://www.tigrisdata.com/llms.txt\n\nReturn:\n- 5-bullet summary\n- Key claims + caveats\n- Who it's for / not for\n- Suggested next steps`;
}

function openWith(url: string): void {
  window.open(url, "_blank", "noopener,noreferrer");
}

function openClaude(): void {
  openWith(`https://claude.ai/new?q=${encodeURIComponent(buildPrompt())}`);
}

function openChatGPT(): void {
  openWith(`https://chatgpt.com/?q=${encodeURIComponent(buildPrompt())}`);
}

function openGemini(): void {
  openWith(
    `https://gemini.google.com/app?q=${encodeURIComponent(buildPrompt())}`
  );
}

function openPerplexity(): void {
  openWith(
    `https://www.perplexity.ai/search?q=${encodeURIComponent(buildPrompt())}`
  );
}

